const normalize = value => String(value || '').toLocaleLowerCase('ru').replace(/ё/g, 'е').replace(/\s+/g, ' ').trim();

const workContext = /регламент|документ|договор|проект|командиров|подраздел|согласован|оплат|расчет|расчёт|сделк|сотрудник|процесс|заявк|план|доставк|зарплат|вознагражден|бизнес|бюджет|смет|закуп|ответствен|этап|внутрен|политик|правил|компан|работ|руководител|заказчик|клиент|отчет|отчёт|срок|форм[аыуе]|поставк/iu;

const offTopicPatterns = [
  /погод|температур|осадк|дожд|снег|ветер|прогноз погоды/iu,
  /курс.{0,35}(доллар|евро|рубл|юан|биткоин|криптовалют)|сколько стоит.{0,35}(доллар|евро|рубл|юан|биткоин|акци[яиюй]|криптовалют)|стоимость.{0,25}(биткоин|криптовалют)/iu,
  /далеко ли до|сколько километров|какое расстояние|расстояние между|как далеко до/iu,
  /\b(?:таллин|тaллинн|москв|санкт-петербург|петербург|казан|минск|хельсинки|ереван|алмат|ташкент|лонд|париж|берлин)\w*/iu,
];

/** Return an out-of-scope category using only cheap local rules; never calls a model. */
export function classifyScope(question, history = []) {
  const text = normalize([question, ...history].join(' '));
  if (!text || workContext.test(text)) return null;
  if (/погод|температур|осадк|дожд|снег|ветер|прогноз погоды/iu.test(text)) return 'weather';
  if (/курс.{0,35}(доллар|евро|рубл|юан|биткоин|криптовалют)|сколько стоит.{0,35}(доллар|евро|рубл|юан|биткоин|акци[яиюй]|криптовалют)|стоимость.{0,25}(биткоин|криптовалют)/iu.test(text)) return 'market';
  if (offTopicPatterns.slice(2).some(pattern => pattern.test(text))) return 'geography';
  return null;
}

export function outOfScopeReply(category) {
  const first = category === 'weather'
    ? 'Погоду я не проверяю — мой прогноз работает только на корпоративных документах.'
    : category === 'market'
      ? 'Курс валют и рыночные цены я не отслеживаю — в моих документах таких котировок нет.'
      : 'Расстояния между городами я не измеряю — мой глобус заканчивается на корпоративной базе.';
  return `${first} 🙂 Спросите меня о внутреннем регламенте или рабочем процессе.`;
}

